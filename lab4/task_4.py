json_prompt = f"""
Проаналізуй наведений текст та поверни результат ВИКЛЮЧНО у форматі валідного JSON (без форматування в блоки markdown типу ```json чи додаткових коментарів), дотримуючись такої структури:
{{
  "topic": "...",
  "key_ideas": [
    "...",
    "..."
  ],
  "keywords": [
    "...",
    "..."
  ],
  "conclusion": "..."
}}

Текст для аналізу:
{source_text}
"""

print("Етап: Надсилання запиту до моделі...\n")
response = client.interactions.create(
    model="gemini-3.5-flash-lite", input=json_prompt
)

raw_output = response.output_text.strip()

if raw_output.startswith("```json"):
  raw_output = raw_output[7:]
if raw_output.startswith("```"):
  raw_output = raw_output[3:]
if raw_output.endswith("```"):
  raw_output = raw_output[:-3]
raw_output = raw_output.strip()

print("Сирий вивід від моделі:\n", raw_output, "\n")

print("Етап: Перевірка та розбір JSON засобами Python...\n")
try:
  parsed_data = json.loads(raw_output)
  print("Успіх! JSON розпарсенно без помилок.")
  print(f"Тема: {parsed_data.get('topic')}")
  print(f"Ключові ідеї: {parsed_data.get('key_ideas')}")
  print(f"Ключові слова: {parsed_data.get('keywords')}")
  print(f"Висновок: {parsed_data.get('conclusion')}")
except json.JSONDecodeError as e:
  print("Помилка: отриманий текст не є валідним JSON!", e)