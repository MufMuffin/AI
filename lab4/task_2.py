print("ПІДХІД 1: ПОСЛІДОВНА ДЕКОМПОЗИЦІЯ З ПЕРЕДАЧЕЮ КОНТЕКСТУ\n")

prompt_1 = f"Виділи виключно список основних понять (термінів) з цього тексту без зайвих привітань:\n{source_text}"
res_1 = client.interactions.create(
    model="gemini-3.5-flash-lite", input=prompt_1
)
concepts = res_1.output_text
print("1. Поняття:\n", concepts, "\n")

prompt_2 = f"На основі тексту та виділених понять виділи лише ключові факти у вигляді нумерованого списку:\nТекст: {source_text}\nПоняття: {concepts}"
res_2 = client.interactions.create(
    model="gemini-3.5-flash-lite", input=prompt_2
)
facts = res_2.output_text
print("2. Факти:\n", facts, "\n")

prompt_3 = f"На основі цих фактів сформуй одне чітке тестове запитання (без варіантів відповідей):\nФакти: {facts}"
res_3 = client.interactions.create(
    model="gemini-3.5-flash-lite", input=prompt_3
)
question = res_3.output_text
print("3. Запитання:\n", question, "\n")

prompt_4 = f"Сформуй 4 варіанти відповідей (A, B, C, D) до цього запитання:\nЗапитання: {question}"
res_4 = client.interactions.create(
    model="gemini-3.5-flash-lite", input=prompt_4
)
options = res_4.output_text
print("4. Варіанти відповідей:\n", options, "\n")

prompt_5 = f"Вкажи правильну літеру варіанта (A, B, C чи D) та коротко обґрунтуй вибір:\nЗапитання: {question}\nВаріанти: {options}"
res_5 = client.interactions.create(
    model="gemini-3.5-flash-lite", input=prompt_5
)
