def ask_gemini(prompt_text: str) -> str:
    while True:
        try:
            response = client.models.generate_content(
                model=MODEL_NAME,
                contents=prompt_text
            )
            time.sleep(2)
            return response.text.strip()
        except ClientError as e:
            if "429" in str(e) or "RESOURCE_EXHAUSTED" in str(e):
                print("\n[!] Перевищено ліміт запитів (429). Очікування 15 секунд...")
                time.sleep(15)
            else:
                raise e


def process_without_chunking(text: str) -> str:
    print("Обробка без Chunking")
    prompt = f"Проаналізуй наданий текст та зроби його детальне та точно структуроване узагальнення:\n\n{text}"
    return ask_gemini(prompt)


def process_with_chunking(text: str) -> tuple[list[str], str]:
    print("\nОбробка з Chunking")
    chunks = [p.strip() for p in text.split("\n\n") if p.strip()]
    
    print(f"Текст розділено на {len(chunks)} абзаців (chunks).")
    
    summaries = []
    for idx, chunk in enumerate(chunks, 1):
        prompt = f"Зроби коротке та точне узагальнення цього фрагмента тексту (Chunk {idx}):\n\n{chunk}"
        summary = ask_gemini(prompt)
        summaries.append(summary)
        print(f"\nSummary for Chunk {idx} \n{summary}")
    
    combined_summaries = "\n\n".join([f"Частина {i+1}: {s}" for i, s in enumerate(summaries)])
    reduce_prompt = f"На основі наступних часткових узагальнень сформулюй один цілісний підсумковий висновок для всього документа:\n\n{combined_summaries}"
    final_summary = ask_gemini(reduce_prompt)
    
    return summaries, final_summary


def process_with_sliding_window(text: str, window_sentences: int = 3, overlap_sentences: int = 1) -> tuple[list[str], str]:
    print("\nОбробка з Sliding Window")

    sentences = re.split(r'(?<=[.!?])\s+', text.replace("\n\n", " "))
    sentences = [s.strip() for s in sentences if s.strip()]
    
    step = window_sentences - overlap_sentences
    chunks = []
    
    for i in range(0, len(sentences), step):
        chunk_group = sentences[i:i + window_sentences]
        chunks.append(" ".join(chunk_group))
        if i + window_sentences >= len(sentences):
            break
            
    print(f"Текст розділено на {len(chunks)} sliding chunks (Вікно: {window_sentences} речень, Перекриття: {overlap_sentences} речення).")
    
    summaries = []
    for idx, chunk in enumerate(chunks, 1):
        prompt = f"Зроби узагальнення цього фрагмента тексту з урахуванням суміжного контексту:\n\n{chunk}"
        summary = ask_gemini(prompt)
        summaries.append(summary)
        print(f"\nSummary for Sliding Chunk {idx} \n{summary}")
        
    combined_summaries = "\n\n".join([f"Фрагмент {i+1}: {s}" for i, s in enumerate(summaries)])
    reduce_prompt = f"На основі наступних часткових узагальнень (зроблених із перекриттям контексту) сформулюй остаточне підсумкове узагальнення:\n\n{combined_summaries}"
    final_summary = ask_gemini(reduce_prompt)
    
    return summaries, final_summary


