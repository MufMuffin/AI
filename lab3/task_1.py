from google import genai

client = genai.Client(api_key="API-KEY")

tasks = {
    "1. Пояснення": "Поясни простими словами, що таке рекурсія в програмуванні.",
    "2. Генерація тексту": "Напиши невеликий текст (до 5 речень) про те, яку мову програмування краще вивчити новачку.",
    "3. Переклад": "Переклади французькою мовою терміни: 'змінна', 'цикл з умовою', 'рекурсія', 'об'єктно-орієнтоване програмування'.",
    "4. Узагальнення": "Узагальни однією фразою текст: 'Об'єктно-орієнтоване програмування (ООП) — це методологія програмування, яка базується на концепції об'єктів, що містять дані у вигляді полів та код у вигляді методів, що дозволяє значно спростити підтримку та масштабування великих програмних систем.'",
    "5. Генерація списку": "Сформуй список із 4 найпопулярніших середовищ розробки (IDE) або редакторів коду для програмування з коротким описом для кожного(2 речення)."
}

for task_name, prompt_text in tasks.items():
    print(f"{task_name}")
    print(f"PROMPT: {prompt_text}\n\n")
    
    interaction = client.interactions.create(
        model="gemini-3.5-flash-lite",
        input=prompt_text
    )
    
    print("Відповідь:")
    print(interaction.output_text)